#!/usr/bin/env node
// Writes lib/firebase_options.dart from the Firebase app settings that
// app/scripts/setup.sh downloads.
//
//   node app/scripts/firebase_options.js <tempDir> <outFile> <projectId>
//
// The temp dir holds apps.json (from `firebase apps:list`), android.json (from
// `firebase apps:sdkconfig ANDROID`) and web.json (the console's init.json or
// `firebase apps:sdkconfig WEB` output).
const fs = require('fs');
const path = require('path');

const [tempDir, outFile, projectId] = process.argv.slice(2);

if (!tempDir || !outFile || !projectId) {
  console.error('usage: firebase_options.js <tempDir> <outFile> <projectId>');
  process.exit(1);
}

const readJson = (name) => {
  const file = path.join(tempDir, name);
  if (!fs.existsSync(file)) return null;
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (error) {
    return null;
  }
};

const apps = readJson('apps.json');
const androidConfig = readJson('android.json');
const webConfig = readJson('web.json');

if (!apps) {
  console.error('apps.json is missing or unreadable');
  process.exit(1);
}

const appList = Array.isArray(apps) ? apps : apps.result || [];
const findApp = (platform) => appList.find((app) => app.platform === platform);

// The iOS settings arrive as the GoogleService-Info.plist, so read the few keys out.
const plistPath = path.join(tempDir, 'GoogleService-Info.plist');
const plistValue = (key) => {
  if (!fs.existsSync(plistPath)) return '';
  const plist = fs.readFileSync(plistPath, 'utf8');
  const match = plist.match(new RegExp(`<key>${key}</key>\\s*<string>([^<]*)</string>`));
  return match ? match[1] : '';
};

const options = [];

options.push({
  platform: 'ios',
  fields: {
    apiKey: plistValue('API_KEY'),
    appId: plistValue('GOOGLE_APP_ID'),
    messagingSenderId: plistValue('GCM_SENDER_ID'),
    projectId: plistValue('PROJECT_ID') || projectId,
    storageBucket: plistValue('STORAGE_BUCKET'),
    iosBundleId: plistValue('BUNDLE_ID'),
  },
});

if (androidConfig && androidConfig.client && androidConfig.client.length) {
  const client = androidConfig.client[0];
  const info = client.client_info || {};
  const androidInfo = info.android_client_info || {};
  options.push({
    platform: 'android',
    fields: {
      apiKey: client.api_key && client.api_key[0] ? client.api_key[0].current_key : '',
      appId: info.mobilesdk_app_id,
      messagingSenderId: String(info.mobilesdk_app_id || '').split(':')[1],
      projectId: (androidConfig.project_info && androidConfig.project_info.project_id) || projectId,
      storageBucket: (androidConfig.project_info && androidConfig.project_info.storage_bucket) || '',
      androidClientId: androidInfo.client_info ? androidInfo.client_info.client_id : '',
    },
  });
} else {
  console.warn('No Android app settings found; the Android build will need a Firebase Android app.');
}

if (webConfig && (webConfig.apiKey || webConfig.client || webConfig.project_info || webConfig.projectId)) {
  // `firebase apps:sdkconfig WEB` returns a flat config in some CLI versions,
  // and the old `__/firebase/init.json` shape in others.
  if (webConfig.client && webConfig.client.length) {
    const client = webConfig.client[0];
    const info = client.client_info || {};
    options.push({
      platform: 'web',
      fields: {
        apiKey: client.api_key && client.api_key[0] ? client.api_key[0].current_key : '',
        appId: info.mobilesdk_app_id,
        messagingSenderId: (webConfig.project_info && (webConfig.project_info.project_number || webConfig.project_info.messagingSenderId)) || String(info.mobilesdk_app_id || '').split(':')[1],
        projectId: (webConfig.project_info && webConfig.project_info.project_id) || projectId,
        storageBucket: (webConfig.project_info && webConfig.project_info.storage_bucket) || '',
      },
    });
  } else if (webConfig.apiKey && webConfig.appId) {
    options.push({
      platform: 'web',
      fields: {
        apiKey: webConfig.apiKey,
        appId: webConfig.appId,
        messagingSenderId: webConfig.messagingSenderId || webConfig.projectNumber,
        projectId: webConfig.projectId || projectId,
        storageBucket: webConfig.storageBucket,
        authDomain: webConfig.authDomain,
        measurementId: webConfig.measurementId,
      },
    });
  }
} else {
  console.warn('No Web app settings found; copy the web config from the Firebase console.');
}

const lines = [
  '// Generated by app/scripts/setup.sh from the Firebase project. Git-ignored.',
  '// ignore_for_file: type=lint',
  "import 'package:firebase_core/firebase_core.dart' show FirebaseOptions;",
  "import 'package:flutter/foundation.dart' show TargetPlatform, defaultTargetPlatform, kIsWeb;",
  '',
  'class DefaultFirebaseOptions {',
  '  static FirebaseOptions get currentPlatform {',
];

const available = options.map((o) => o.platform);
if (available.includes('web')) lines.push('    if (kIsWeb) return web;');
lines.push('    switch (defaultTargetPlatform) {');
if (available.includes('android')) {
  lines.push('      case TargetPlatform.android:');
  lines.push('        return android;');
}
if (available.includes('ios')) {
  lines.push('      case TargetPlatform.iOS:');
  lines.push('        return ios;');
}
lines.push('      default:');
lines.push("        throw UnsupportedError('BakeOut has no config for this platform.');");
lines.push('    }');
lines.push('  }');

for (const option of options) {
  lines.push('');
  lines.push(`  static const FirebaseOptions ${option.platform} = FirebaseOptions(`);
  for (const [key, value] of Object.entries(option.fields)) {
    if (!value) continue;
    lines.push(`    ${key}: ${JSON.stringify(value)},`);
  }
  lines.push('  );');
}
lines.push('}');

fs.writeFileSync(outFile, lines.join('\n') + '\n');
console.log(`Wrote ${outFile} with ${options.map((o) => o.platform).join(', ')}.`);

// A platform with no settings would break the app at start-up, so say so plainly.
const missing = ['ios', 'android', 'web'].filter((p) => !options.some((o) => o.platform === p));
if (missing.length) {
  console.log(`Still missing: ${missing.join(', ')}.`);
}
